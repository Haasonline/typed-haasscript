//! How the primitive types are written in annotations, in messages and in
//! generated declarations. One spelling each, so reading a type name and
//! writing one always agree.

pub(crate) const ANY: &str = "any";
pub(crate) const UNKNOWN: &str = "unknown";
pub(crate) const NEVER: &str = "never";
pub(crate) const NIL: &str = "nil";
pub(crate) const BOOLEAN: &str = "boolean";
pub(crate) const NUMBER: &str = "number";
pub(crate) const STRING: &str = "string";
